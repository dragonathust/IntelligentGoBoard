void WS2812B_setPixelColor(uint16_t n, uint32_t c)
{
   uint8_t r,g,b;
  
   r = (uint8_t)(c >> 16),
   g = (uint8_t)(c >>  8),
   b = (uint8_t)c;

   uint8_t *bptr = pixels + (n<<3) + n + PEAMBLE_BYTES;
   uint8_t *tPtr = (uint8_t *)encoderLookup + g*2 + g;// need to index 3 x g into the lookup
   
   *bptr++ = *tPtr++;
   *bptr++ = *tPtr++;
   *bptr++ = *tPtr++;

   tPtr = (uint8_t *)encoderLookup + r*2 + r;
   *bptr++ = *tPtr++;
   *bptr++ = *tPtr++;
   *bptr++ = *tPtr++;   
   
   tPtr = (uint8_t *)encoderLookup + b*2 + b;
   *bptr++ = *tPtr++;
   *bptr++ = *tPtr++;
   *bptr++ = *tPtr++;
}

/*
*	Sets the encoded pixel data to turn all the LEDs off.
*/
void WS2812B_clear() 
{
	uint8_t * bptr= pixels + PEAMBLE_BYTES;// Note first byte in the buffer is a preable and is always zero. hence the +1
	uint8_t *tPtr;

	for(int i=0;i< (NUM_LEDS *3);i++)
	{
	   tPtr = (uint8_t *)encoderLookup;
   	   *bptr++ = *tPtr++;
	   *bptr++ = *tPtr++;
	   *bptr++ = *tPtr++;	
	}
}

